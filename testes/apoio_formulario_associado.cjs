const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const internos=[{name:'campo__10.1'}], externos=[{name:'campo__10.9'}];
const eventos={},recebidos=[];
const form={id:'formulario-bloco-10',querySelectorAll(){return internos;},dispatchEvent(e){recebidos.push(e.type);}};
const area={querySelectorAll(){return externos;},addEventListener(t,f){eventos[t]=f;}};
externos[0].form=form;
const categoria={value:'Outra Secretaria',addEventListener(t,f){this.change=f;}};
const modo={value:'identificado',addEventListener(t,f){this.change=f;}};
const complemento={open:true};
const editor={dataset:{categoriasMunicipais:JSON.stringify(['Outra Secretaria'])},querySelector(s){return s.includes('__categoria')?categoria:s.includes('__modalidade')?modo:complemento;}};
const contexto={window:{},Event:class{constructor(type){this.type=type;}},document:{querySelector(){return area;},querySelectorAll(s){return s==='[data-destinatario-editor]'?[editor]:[area];}}};
vm.runInNewContext(fs.readFileSync('app/estaticos/formulario_associado_form1.js','utf8'),contexto);
assert.deepEqual(Array.from(contexto.window.elementosFormularioForm1(form,'[name]')), [...internos,...externos]);
const salvar={matches(s){return s==='button[type="submit"]';}};
form.elements=[salvar];
assert.equal(contexto.window.elementosFormularioForm1(form,'button[type="submit"]').includes(salvar),true);
eventos.input({target:externos[0]}); eventos.change({target:externos[0]});
assert.deepEqual(recebidos,['input','change']);
assert.equal(complemento.open,false);
categoria.value='Empresa contratada';categoria.change();assert.equal(complemento.open,true);
categoria.value='Outra Secretaria';modo.value='requisicao_eventual';modo.change();assert.equal(complemento.open,true);
modo.value='nao_determinavel';modo.change();assert.equal(complemento.open,true);
modo.value='identificado';modo.change();assert.equal(complemento.open,false);
assert.equal(externos[0].name,'campo__10.9');
console.log('Associação, avisos de edição e orientação por categoria/modo: aprovados.');
